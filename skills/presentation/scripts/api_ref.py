#!/usr/bin/env python3
"""
Print the build API -- every public function, its signature and what it does.

    scripts/api_ref.py                 # all of it (it is references/api.md)
    scripts/api_ref.py draw            # one module
    scripts/api_ref.py --write         # regenerate references/api.md

Generated from the code, so it cannot drift from it: a field run spent some
forty shell calls reading ``draw.py`` and ``template.py`` with ``sed`` to find
out what ``D.text`` takes and how to style one paragraph.  Look it up here,
then read ``references/drawing.md`` for how to compose with it.
"""

import argparse
import importlib
import inspect
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

OUTPUT = HERE.parent / "references" / "api.md"

#: (module, how a build script imports it), in reading order.
MODULES = (
    ("office.deckbuild", "from office.deckbuild import build_deck, build_parts"),
    ("office.template", "from office.template import set_title, retext, ..."),
    ("office.draw", "from office import draw as D"),
    ("office.impress", "from office.impress import mm, set_notes, ..."),
)

SUMMARY_CHARS = 320


def _summary(obj) -> str:
    """The docstring's first paragraph on one line, cut at a sentence end."""
    doc = inspect.getdoc(obj) or ""
    first = re.split(r"\n\s*\n", doc.strip(), maxsplit=1)[0]
    first = " ".join(first.split())
    if len(first) > SUMMARY_CHARS:
        cut = first.rfind(". ", 0, SUMMARY_CHARS)
        first = (first[:cut + 1] if cut > 80
                 else first[:SUMMARY_CHARS].rstrip() + " ...")
    return first


def _keywords(obj) -> str:
    """A ``**kw`` function's "Keywords: ..." paragraph -- its real signature."""
    try:
        params = inspect.signature(obj).parameters.values()
    except (TypeError, ValueError):
        return ""
    if not any(p.kind is inspect.Parameter.VAR_KEYWORD for p in params):
        return ""
    for para in re.split(r"\n\s*\n", inspect.getdoc(obj) or ""):
        if para.lstrip().startswith("Keywords:"):
            return " " + " ".join(para.split())
    return ""


def _signature(obj) -> str:
    try:
        sig = str(inspect.signature(obj))
    except (TypeError, ValueError):
        return "(...)"
    # Defaults that are objects print their repr with an address; no use.
    return re.sub(r"<object object at 0x[0-9a-f]+>", "KEEP", sig)


def _public(module):
    """Functions and classes defined in ``module``, in source order."""
    out = []
    for name, obj in vars(module).items():
        if name.startswith("_"):
            continue
        if not (inspect.isfunction(obj) or inspect.isclass(obj)):
            continue
        if getattr(obj, "__module__", None) != module.__name__:
            continue
        try:
            line = inspect.getsourcelines(obj)[1]
        except (OSError, TypeError):
            line = 0
        out.append((line, name, obj))
    return [(name, obj) for _, name, obj in sorted(out, key=lambda t: t[0])]


def _constants(module):
    return [(n, v) for n, v in vars(module).items()
            if n.isupper() and not n.startswith("_")
            and isinstance(v, (int, float, str)) and not isinstance(v, bool)]


def render(names=None) -> str:
    lines = ["# Build API reference", "",
             "Generated by `scripts/api_ref.py` from the code -- do not edit; "
             "run `scripts/api_ref.py --write`. Signatures and the first "
             "paragraph of each docstring. How to compose with these: "
             "`references/drawing.md`; the recipe: `SKILL.md`.", "",
             "Geometry is 1/100 mm (`mm()`, `pt()`); colours are `0xRRGGBB` "
             "integers -- by name through `D.color(\"accent\")`, never typed "
             "as hex; font sizes are points.", ""]
    for modname, how in MODULES:
        short = modname.split(".")[-1]
        if names and short not in names:
            continue
        module = importlib.import_module(modname)
        lines += [f"## {modname}", "", f"`{how}`", ""]
        consts = _constants(module)
        if consts:
            shown = ", ".join(f"`{n}`={v!r}" if isinstance(v, str)
                              else f"`{n}`={v:g}" if isinstance(v, float)
                              else f"`{n}`={v}"
                              for n, v in consts)
            lines += [f"Constants: {shown}", ""]
        for name, obj in _public(module):
            kind = "class " if inspect.isclass(obj) else ""
            lines.append(f"- **{kind}`{name}{_signature(obj)}`** -- "
                         f"{_summary(obj) or '(undocumented)'}"
                         f"{_keywords(obj)}")
            if inspect.isclass(obj):
                for mname, meth in vars(obj).items():
                    if mname.startswith("_"):
                        continue
                    if isinstance(meth, property):
                        lines.append(f"  - `.{mname}` -- "
                                     f"{_summary(meth.fget) or 'property'}")
                    elif inspect.isfunction(meth):
                        lines.append(f"  - `.{mname}{_signature(meth)}` -- "
                                     f"{_summary(meth) or '(undocumented)'}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description="The build API, from the code")
    parser.add_argument("modules", nargs="*",
                        help="deckbuild, template, draw, impress (default: all)")
    parser.add_argument("--write", action="store_true",
                        help=f"Write {OUTPUT.relative_to(HERE.parent)}")
    args = parser.parse_args()
    known = {m.split(".")[-1] for m, _ in MODULES}
    unknown = set(args.modules) - known
    if unknown:
        print(f"Error: unknown module(s) {', '.join(sorted(unknown))}; "
              f"pick from {', '.join(sorted(known))}", file=sys.stderr)
        return 2
    text = render(set(args.modules) or None)
    if args.write:
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
